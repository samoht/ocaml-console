(* The tape that records the build in the theme its argument names, if any:
   display.gif in the default theme, <theme>.gif in another, on that theme's
   background. *)

(* Text that reads on the background: dark on a light one, light on a dark
   one. *)
let vhs_theme name =
  match
    Option.bind (List.assoc_opt name Console.Theme.all) Console.Theme.background
  with
  | None -> "Builtin Dark"
  | Some bg ->
      let r, g, b = Console.Color.to_rgb bg in
      let light = (r * 299) + (g * 587) + (b * 114) > 128_000 in
      let fg = if light then "#333333" else "#dddddd" in
      Fmt.str
        {|{ "name": "demo", "background": "#%02x%02x%02x", "foreground": "%s", "cursor": "%s", "selection": "%s" }|}
        r g b fg fg fg

let () =
  let theme = if Array.length Sys.argv > 1 then Some Sys.argv.(1) else None in
  let gif, args, what =
    match theme with
    | None -> ("display", "", "a build whose running steps are redrawn in place")
    | Some name ->
        (name, " " ^ name, "the build in " ^ name ^ ", its table's frame moving")
  in
  match
    Vhs.tape
      ~settings:
        [
          Shell Bash;
          Font_size 18;
          Width 1000;
          Height 640;
          Theme (vhs_theme (Option.value theme ~default:"default"));
          Padding 20;
          Typing_speed (Ms 20);
        ]
      ~outputs:[ "examples/display/" ^ gif ^ ".gif" ]
      [
        Vhs.raw ("# Generated by tape.ml: " ^ what ^ ".");
        Vhs.raw {|Require "dune"|};
        Vhs.hidden
          [
            Vhs.type' "dune build examples/display/main.exe && clear\n";
            Vhs.wait ~timeout:(Ms 300_000) Prompt;
          ];
        Vhs.type' ("dune exec examples/display/main.exe" ^ args ^ "\n");
        Vhs.wait ~timeout:(Ms 60_000) (Screen "build complete");
        Vhs.sleep (Ms 2000);
      ]
  with
  | Ok t -> print_string (Vhs.to_string t)
  | Error e ->
      prerr_endline e;
      exit 1
