(* The tape that records two builds side by side, under a table of their
   status and above the summary. *)

let () =
  match
    Vhs.tape
      ~settings:
        [
          Shell Bash;
          Font_size 16;
          Width 1100;
          Height 520;
          Theme "Builtin Dark";
          Padding 20;
          Typing_speed (Ms 20);
        ]
      ~outputs:[ "examples/columns/columns.gif" ]
      [
        Vhs.raw "# Generated by tape.ml: two builds side by side.";
        Vhs.raw {|Require "dune"|};
        Vhs.hidden
          [
            Vhs.type'
              "dune build examples/columns/main.exe && alias \
               columns=$PWD/_build/default/examples/columns/main.exe && clear\n";
            Vhs.wait ~timeout:(Ms 300_000) Prompt;
          ];
        Vhs.type' "columns\n";
        Vhs.wait ~timeout:(Ms 60_000) Prompt;
        Vhs.sleep (Ms 2000);
      ]
  with
  | Ok t -> print_string (Vhs.to_string t)
  | Error e ->
      Fmt.epr "%a@." Vhs.pp_error e;
      exit 1
