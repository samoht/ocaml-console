(* The tape that screenshots the theme demo in the theme its argument names,
   on that theme's background. *)

let backgrounds =
  [
    ("unicode", None);
    ("dos", Some "#000000");
    ("matrix", Some "#000000");
    ("rainbow", None);
    ("dracula", Some "#282a36");
    ("nord", Some "#2e3440");
    ("solarized-dark", Some "#002b36");
    ("solarized-light", Some "#fdf6e3");
    ("gruvbox-dark", Some "#282828");
    ("gruvbox-light", Some "#fbf1c7");
    ("catppuccin-latte", Some "#eff1f5");
    ("catppuccin-mocha", Some "#1e1e2e");
    ("tokyo-night", Some "#1a1b26");
    ("one-dark", Some "#282c34");
    ("monokai", Some "#272822");
    ("github-dark", Some "#0d1117");
    ("github-light", Some "#ffffff");
  ]

(* Text that reads on the background: dark on a light one, light on a dark
   one. *)
let vhs_theme = function
  | None -> "Builtin Dark"
  | Some bg ->
      let c i = int_of_string ("0x" ^ String.sub bg i 2) in
      let light = (c 1 * 299) + (c 3 * 587) + (c 5 * 114) > 128_000 in
      let fg = if light then "#333333" else "#dddddd" in
      Fmt.str
        {|{ "name": "demo", "background": "%s", "foreground": "%s", "cursor": "%s", "selection": "%s" }|}
        bg fg fg fg

let () =
  let name = Sys.argv.(1) in
  let bg = List.assoc name backgrounds in
  match
    Vhs.tape
      ~settings:
        [
          Shell Bash;
          Font_size 16;
          Width 900;
          Height 520;
          Padding 20;
          Typing_speed (Ms 5);
          Theme (vhs_theme bg);
        ]
      ~outputs:[ "_build/themes/" ^ name ^ ".txt" ]
      [
        Vhs.raw ("# Generated by tape.ml: the theme demo in " ^ name ^ ".");
        Vhs.raw {|Require "dune"|};
        Vhs.hidden
          [
            Vhs.type' "dune build examples/themes/main.exe && clear\n";
            Vhs.wait ~timeout:(Ms 300_000) Prompt;
          ];
        Vhs.type' ("dune exec examples/themes/main.exe " ^ name ^ "\n");
        Vhs.wait ~timeout:(Ms 60_000) (Screen "unused variable");
        Vhs.sleep (Ms 300);
        Fmt.kstr Vhs.raw "Screenshot %S" ("examples/themes/" ^ name ^ ".png");
        Vhs.wait ~timeout:(Ms 60_000) Prompt;
      ]
  with
  | Ok t -> print_string (Vhs.to_string t)
  | Error e ->
      prerr_endline e;
      exit 1
