(* The tape that screenshots the theme demo in the theme its argument names,
   on that theme's background: the one place that says how the gallery is
   recorded. The README shows the eighteen screenshots as one grid,
   gallery.png, in the order of Theme.all: each cropped to 900x400 from
   y = 42 (below the command line), scaled to 600 wide and laid out three
   to a row, 8 pixels apart, with ffmpeg's xstack filter. *)

(* Text that reads on the background: dark on a light one, light on a dark
   one. *)
let vhs_theme theme =
  match Console.Theme.background theme with
  | None -> "Builtin Dark"
  | Some bg ->
      let r, g, b = Console.Color.to_rgb bg in
      let light = (r * 299) + (g * 587) + (b * 114) > 128_000 in
      let fg = if light then "#333333" else "#dddddd" in
      Fmt.str
        {|{ "name": "demo", "background": "#%02x%02x%02x", "foreground": "%s", "cursor": "%s", "selection": "%s" }|}
        r g b fg fg fg

let () =
  let name = Sys.argv.(1) in
  let theme = List.assoc name Console.Theme.all in
  match
    K7.tape
      ~settings:
        [
          Shell Bash;
          Font_size 16;
          Width 900;
          Height 520;
          Padding 20;
          Typing_speed (Ms 5);
          Theme (vhs_theme theme);
        ]
      ~outputs:[ "_build/themes/" ^ name ^ ".txt" ]
      [
        K7.raw ("# Generated by tape.ml: the theme demo in " ^ name ^ ".");
        K7.raw {|Require "dune"|};
        K7.hidden
          [
            K7.type' "dune build examples/themes/main.exe && clear\n";
            K7.wait ~timeout:(Ms 300_000) Prompt;
          ];
        K7.type' ("dune exec examples/themes/main.exe " ^ name ^ "\n");
        K7.wait ~timeout:(Ms 60_000) (Screen "unused variable");
        K7.sleep (Ms 300);
        Fmt.kstr K7.raw "Screenshot %S" ("examples/themes/" ^ name ^ ".png");
        K7.wait ~timeout:(Ms 60_000) Prompt;
      ]
  with
  | Ok t -> print_string (K7.to_string t)
  | Error e ->
      Fmt.epr "%a@." K7.pp_error e;
      exit 1
