(* The tape that records the README's first program, [check], run in the
   default theme and then in Theme.rainbow. *)

let () =
  let run args =
    [
      Vhs.type' ("check" ^ args ^ "\n");
      Vhs.wait ~timeout:(Ms 60_000) Prompt;
      Vhs.sleep (Ms 1500);
    ]
  in
  match
    Vhs.tape
      ~settings:
        [
          Shell Bash;
          Font_size 16;
          Width 900;
          Height 560;
          Theme "Builtin Dark";
          Padding 20;
          Typing_speed (Ms 20);
        ]
      ~outputs:[ "examples/quickstart/quickstart.gif" ]
      ([
         Vhs.raw "# Generated by tape.ml: the README's first program.";
         Vhs.raw {|Require "dune"|};
         Vhs.hidden
           [
             Vhs.type'
               "dune build examples/quickstart/main.exe && alias \
                check=$PWD/_build/default/examples/quickstart/main.exe && clear\n";
             Vhs.wait ~timeout:(Ms 300_000) Prompt;
           ];
       ]
      @ run "" @ run " --theme=rainbow")
  with
  | Ok t -> print_string (Vhs.to_string t)
  | Error e ->
      Fmt.epr "%a@." Vhs.pp_error e;
      exit 1
