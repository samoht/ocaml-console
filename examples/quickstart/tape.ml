(* The tape that records the README's first program, [check], run in the
   default theme and then in Theme.rainbow. *)

let () =
  let run args =
    [
      K7.type' ("check" ^ args ^ "\n");
      K7.wait ~timeout:(Ms 60_000) Prompt;
      K7.sleep (Ms 1500);
    ]
  in
  match
    K7.tape
      ~settings:
        [
          Shell Bash;
          Font_size 16;
          Width 900;
          Height 560;
          Theme "Builtin Dark";
          Padding 20;
          Typing_speed (Ms 20);
        ]
      ~outputs:[ "examples/quickstart/quickstart.gif" ]
      ([
         K7.raw "# Generated by tape.ml: the README's first program.";
         K7.raw {|Require "dune"|};
         K7.hidden
           [
             K7.type'
               "dune build examples/quickstart/main.exe && alias \
                check=$PWD/_build/default/examples/quickstart/main.exe && clear\n";
             K7.wait ~timeout:(Ms 300_000) Prompt;
           ];
       ]
      @ run "" @ run " --theme=rainbow")
  with
  | Ok t -> print_string (K7.to_string t)
  | Error e ->
      Fmt.epr "%a@." K7.pp_error e;
      exit 1
